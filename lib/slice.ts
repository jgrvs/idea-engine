// Slice stage: build ONE feature of a validated idea as real, running code.
//
// The flow is deliberately boxed in:
//   1. Scaffold a project from the pinned template in templates/slice-next and
//      install its dependencies. The dependency list never comes from a model.
//   2. Run a tool-using agent that can list, read, and write files inside that
//      project and ask for a build. It cannot touch package.json or any config,
//      cannot write outside the project, and has a hard cap on turns, builds,
//      and files.
//   3. Run the authoritative build ourselves. Red means slice_failed with the
//      log attached.
//   4. Smoke test: start the built app on a loopback port, request /, record
//      the status. Then a human opens it and marks it works or broken.
//
// Building and starting the slice executes code a model wrote, on this
// machine. It runs with a stripped environment (no API key, nothing inherited
// from the dashboard's process) and binds to 127.0.0.1 only, but it is not a
// sandbox: it has the same filesystem access as the user running the engine.

import { spawn, type ChildProcess } from 'child_process'
import fs from 'fs'
import net from 'net'
import path from 'path'
import Anthropic from '@anthropic-ai/sdk'
import { addArtifact, getArtifact, getDb, logUsage, setStageProgress } from './db'
import { getClient, MODELS } from './llm'
import { composeSliceBrief, SLICE_SYSTEM } from './prompts'
import { sliceDir } from './sandbox'
import { transition } from './stages'
