// ── Limits ───────────────────────────────────────────────────────────────────

const MAX_TURNS = 40              // model calls per slice
const MAX_BUILDS = 6              // run_build calls the agent may make
const MAX_FILES = 30              // files the agent may create or change (hard stop)
const SCOPE_FILE_THRESHOLD = 15   // files added beyond the template before a scope flag
const MAX_FILE_BYTES = 80_000     // largest single file the agent may write
const READ_CHUNK = 40_000         // characters returned per read_file call
const MAX_OUTPUT = 200_000        // captured process output kept in memory
const INSTALL_TIMEOUT_MS = 10 * 60_000
const BUILD_TIMEOUT_MS = 6 * 60_000
const SMOKE_TIMEOUT_MS = 45_000

const TEMPLATE_DIR = path.join(/*turbopackIgnore: true*/ process.cwd(), 'templates', 'slice-next')

// Files the agent may read but never write: the dependency list and build
// config are fixed by the template.
const READ_ONLY_FILES = new Set([
  'package.json', 'package-lock.json', 'next.config.ts', 'tsconfig.json', 'postcss.config.mjs', 'next-env.d.ts',
])
const BLOCKED_DIRS = new Set(['node_modules', '.next', '.git', 'data'])
const DOCS_PREFIX = 'node_modules/next/dist/docs/'
// Left out of the template diff: generated by install or build, not by the agent.
const DIFF_SKIP = new Set(['package-lock.json', 'next-env.d.ts', 'slice-build.log', 'tsconfig.tsbuildinfo'])
// Shown to the agent up front so it does not spend turns reading them.
const BRIEF_FILES = ['package.json', 'app/layout.tsx', 'app/page.tsx', 'app/globals.css', 'lib/db.ts']

// ── Child processes ──────────────────────────────────────────────────────────

// Environment for anything that runs template or model-written code. Built
// from an allowlist so the API key, the dashboard's own NODE_ENV, and Next's
// internal variables never reach it.
function childEnv(extra: Record<string, string> = {}): NodeJS.ProcessEnv {
  const allow = [
    'PATH', 'Path', 'PATHEXT', 'SystemRoot', 'SYSTEMROOT', 'windir', 'ComSpec', 'COMSPEC',
    'TEMP', 'TMP', 'TMPDIR', 'HOME', 'USERPROFILE', 'HOMEDRIVE', 'HOMEPATH',
    'APPDATA', 'LOCALAPPDATA', 'ProgramData', 'ProgramFiles', 'ProgramFiles(x86)', 'CommonProgramFiles',
    'NUMBER_OF_PROCESSORS', 'PROCESSOR_ARCHITECTURE', 'OS', 'LANG', 'LC_ALL', 'SHELL', 'USER', 'USERNAME', 'LOGNAME',
  ]
  const env: Record<string, string> = {}
  for (const key of allow) {
    const v = process.env[key]
    if (v != null) env[key] = v
  }
  // Next's typings make NODE_ENV a required key of ProcessEnv; this env sets it only when a caller asks.
  return { ...env, NEXT_TELEMETRY_DISABLED: '1', NO_COLOR: '1', FORCE_COLOR: '0', CI: '1', ...extra } as unknown as NodeJS.ProcessEnv
}

function killTree(child: ChildProcess) {
  if (!child.pid) return
  if (process.platform === 'win32') {
    // .kill() on Windows leaves grandchildren (build workers) running.
    spawn('taskkill', ['/pid', String(child.pid), '/T', '/F'], { windowsHide: true }).on('error', () => {})
  } else {
    child.kill('SIGKILL')
  }
}

// Kill and wait until the process has really gone. On Windows a server that
// was just told to die can hold its files open for a moment longer, and the
// next step (resetting the directory for a retry) would fail on the lock.
function stop(child: ChildProcess, graceMs = 8000): Promise<void> {
  return new Promise(resolve => {
    if (child.exitCode !== null || child.signalCode !== null) return resolve()
    const timer = setTimeout(resolve, graceMs)
    child.once('exit', () => { clearTimeout(timer); resolve() })
    killTree(child)
  })
}

const stripAnsi = (s: string) => s.replace(/\x1b\[[0-9;]*[A-Za-z]/g, '')
const tail = (s: string, lines: number) => s.trimEnd().split('\n').slice(-lines).join('\n')

interface RunResult { code: number | null; output: string; timedOut: boolean }

function run(file: string, args: string[], opts: { cwd: string; env: NodeJS.ProcessEnv; timeoutMs: number; shell?: boolean }): Promise<RunResult> {
  return new Promise(resolve => {
    // With a shell, pass one fixed command string (the only shell use is `npm
    // install`, whose arguments are constants).
    const child = opts.shell
      ? spawn([file, ...args].join(' '), { cwd: opts.cwd, env: opts.env, shell: true, windowsHide: true })
      : spawn(file, args, { cwd: opts.cwd, env: opts.env, windowsHide: true })

    let output = ''
    const collect = (d: Buffer) => {
      output += d.toString()
      if (output.length > MAX_OUTPUT) output = output.slice(-MAX_OUTPUT)
    }
    child.stdout?.on('data', collect)
    child.stderr?.on('data', collect)

    let timedOut = false
    let settled = false
    const done = (code: number | null, extra = '') => {
      if (settled) return
      settled = true
      clearTimeout(timer)
      resolve({ code, output: stripAnsi(output + extra), timedOut })
    }
    const timer = setTimeout(() => { timedOut = true; killTree(child) }, opts.timeoutMs)
    child.on('error', err => done(null, `\n${err.message}`))
    child.on('close', code => done(code))
  })
}

const nextBin = (dir: string) => path.join(dir, 'node_modules', 'next', 'dist', 'bin', 'next')

function runBuild(dir: string): Promise<RunResult> {
  return run(process.execPath, [nextBin(dir), 'build'], {
    cwd: dir, env: childEnv({ NODE_ENV: 'production' }), timeoutMs: BUILD_TIMEOUT_MS,
  })
}

function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const srv = net.createServer()
    srv.on('error', reject)
    srv.listen(0, '127.0.0.1', () => {
      const addr = srv.address()
      srv.close(() => (addr && typeof addr === 'object' ? resolve(addr.port) : reject(new Error('no port'))))
    })
  })
}

const sleep = (ms: number) => new Promise(r => setTimeout(r, ms))

// Start the built app on a loopback port, request the home page once, record
// the status, and shut it down. This proves the slice boots and renders; it
// does not prove the feature is right, which is the human's half of the gate.
async function smokeTest(dir: string): Promise<{ status: number | null; ok: boolean; output: string }> {
  const port = await freePort()
  const child = spawn(process.execPath, [nextBin(dir), 'start', '-H', '127.0.0.1', '-p', String(port)], {
    cwd: dir, env: childEnv({ NODE_ENV: 'production' }), windowsHide: true,
  })
  let output = ''
  const collect = (d: Buffer) => { output = (output + d.toString()).slice(-20_000) }
  child.stdout?.on('data', collect)
  child.stderr?.on('data', collect)
  let exited = false
  child.on('exit', () => { exited = true })
  child.on('error', () => { exited = true })

  try {
    const deadline = Date.now() + SMOKE_TIMEOUT_MS
    while (Date.now() < deadline && !exited) {
      await sleep(700)
      try {
        const res = await fetch(`http://127.0.0.1:${port}/`, {
          redirect: 'manual', cache: 'no-store', signal: AbortSignal.timeout(10_000),
        })
        await res.text().catch(() => '')
        return { status: res.status, ok: res.status >= 200 && res.status < 400, output: stripAnsi(output) }
      } catch { /* not listening yet */ }
    }
    return { status: null, ok: false, output: stripAnsi(output) }
  } finally {
    await stop(child)
  }
}

// ── Project files ────────────────────────────────────────────────────────────

// Relative, forward-slash paths of every project file, skipping installed and
// generated directories.
function listProjectFiles(root: string): string[] {
  const out: string[] = []
  const walk = (dir: string, prefix: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (prefix === '' && BLOCKED_DIRS.has(entry.name)) continue
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name
      if (entry.isDirectory()) walk(path.join(dir, entry.name), rel)
      else if (entry.isFile()) out.push(rel)
    }
  }
  walk(root, '')
  return out.sort()
}

// Reset the slice directory to the template. node_modules and the lockfile are
// kept so a retry does not reinstall.
function scaffold(dir: string) {
  if (path.basename(dir) !== 'slice') throw new Error(`Refusing to scaffold into ${dir}`)
  fs.mkdirSync(dir, { recursive: true })
  for (const entry of fs.readdirSync(dir)) {
    if (entry === 'node_modules' || entry === 'package-lock.json') continue
    // Retries cover a file still held for a moment by a process that just exited.
    fs.rmSync(path.join(dir, entry), { recursive: true, force: true, maxRetries: 10, retryDelay: 300 })
  }
  fs.cpSync(TEMPLATE_DIR, dir, { recursive: true })
}

function needsInstall(dir: string): boolean {
  try {
    const pinned = JSON.parse(fs.readFileSync(path.join(TEMPLATE_DIR, 'package.json'), 'utf8')).dependencies as Record<string, string>
    for (const [name, version] of Object.entries(pinned)) {
      const installed = JSON.parse(fs.readFileSync(path.join(dir, 'node_modules', ...name.split('/'), 'package.json'), 'utf8')).version
      if (installed !== version) return true
    }
    return false
  } catch {
    return true
  }
}

// ── Agent tools ──────────────────────────────────────────────────────────────

// An error the agent should see and can act on, as opposed to a bug in here.
class ToolError extends Error {}

// Resolve a model-supplied path inside the project. The path is untrusted:
// reject anything absolute, anything that climbs out, and anything aimed at a
// directory or file the agent has no business in.
function resolveInProject(root: string, raw: unknown, mode: 'read' | 'write'): { abs: string; rel: string } {
  if (typeof raw !== 'string' || !raw.trim()) throw new ToolError('path must be a non-empty string')
  const norm = raw.trim().replace(/\\/g, '/')
  if (norm.includes('\0') || norm.startsWith('/') || /^[a-zA-Z]:/.test(norm)) {
    throw new ToolError('path must be relative to the project root')
  }
  const parts = norm.split('/').filter(p => p && p !== '.')
  if (!parts.length || parts.includes('..')) throw new ToolError('path may not contain .. segments')
  const rel = parts.join('/')
  const abs = path.resolve(root, ...parts)
  if (!abs.startsWith(root + path.sep)) throw new ToolError('path escapes the project root')

  if (BLOCKED_DIRS.has(parts[0])) {
    const isDocs = mode === 'read' && (rel + '/').startsWith(DOCS_PREFIX)
    if (!isDocs) {
      throw new ToolError(mode === 'read'
        ? `${parts[0]}/ is not readable, except the Next.js docs under ${DOCS_PREFIX}`
        : `${parts[0]}/ is not writable`)
    }
  }
  if (mode === 'write') {
    if (READ_ONLY_FILES.has(rel)) throw new ToolError(`${rel} is read-only: dependencies and build config are fixed by the template`)
    const base = parts[parts.length - 1]
    if (base.startsWith('.env') || base === '.npmrc') throw new ToolError(`${base} may not be written`)
  }
  return { abs, rel }
}

