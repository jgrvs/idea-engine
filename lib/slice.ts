interface AgentState {
  root: string
  written: Set<string>
  builds: number
  lastBuildOk: boolean
  dirtySinceBuild: boolean
  finished: { summary: string; howToTry: string } | null
}

// Run one tool call. Inputs arrive from a streamed response without server
// validation, so every field is checked here before it is used.
async function execTool(state: AgentState, name: string, rawInput: unknown): Promise<string> {
  const input = (rawInput && typeof rawInput === 'object' ? rawInput : {}) as Record<string, unknown>

  switch (name) {
    case 'list_files': {
      if (input.dir == null || input.dir === '' || input.dir === '.') return listProjectFiles(state.root).join('\n')
      const { abs } = resolveInProject(state.root, input.dir, 'read')
      if (!fs.existsSync(abs) || !fs.statSync(abs).isDirectory()) throw new ToolError('not a directory')
      return fs.readdirSync(abs, { withFileTypes: true })
        .map(e => (e.isDirectory() ? `${e.name}/` : e.name)).sort().join('\n') || '(empty)'
    }

    case 'read_file': {
      const { abs, rel } = resolveInProject(state.root, input.path, 'read')
      if (!fs.existsSync(abs) || !fs.statSync(abs).isFile()) throw new ToolError(`${rel} does not exist`)
      const text = fs.readFileSync(abs, 'utf8')
      const offset = Number.isInteger(input.offset) && (input.offset as number) > 0 ? (input.offset as number) : 0
      if (offset === 0 && text.length <= READ_CHUNK) return text
      const chunk = text.slice(offset, offset + READ_CHUNK)
      const end = offset + chunk.length
      const more = end < text.length ? ` Pass offset ${end} for the next part.` : ' This is the end of the file.'
      return `[${rel}: characters ${offset}-${end} of ${text.length}.${more}]\n${chunk}`
    }

    case 'write_file': {
      const { abs, rel } = resolveInProject(state.root, input.path, 'write')
      if (typeof input.content !== 'string') throw new ToolError('content must be a string holding the complete file')
      if (Buffer.byteLength(input.content) > MAX_FILE_BYTES) throw new ToolError(`file is larger than ${MAX_FILE_BYTES} bytes; split it up`)
      if (!state.written.has(rel) && state.written.size >= MAX_FILES) {
        throw new ToolError(`file limit reached (${MAX_FILES}). This slice is one feature: finish it with the files you have.`)
      }
      fs.mkdirSync(path.dirname(abs), { recursive: true })
      fs.writeFileSync(abs, input.content, 'utf8')
      state.written.add(rel)
      state.dirtySinceBuild = true
      return `wrote ${rel} (${input.content.split('\n').length} lines)`
    }

    case 'run_build': {
      if (state.builds >= MAX_BUILDS) throw new ToolError(`build limit reached (${MAX_BUILDS}). Call finish; the final build runs after you do.`)
      state.builds++
      const res = await runBuild(state.root)
      state.lastBuildOk = res.code === 0 && !res.timedOut
      state.dirtySinceBuild = false
      const head = res.timedOut ? 'build timed out' : `exit code ${res.code}`
      return `${head} (build ${state.builds} of ${MAX_BUILDS})\n${tail(res.output, 90).slice(-8000)}`
    }

    case 'finish': {
      if (typeof input.summary !== 'string' || typeof input.how_to_try !== 'string') {
        throw new ToolError('finish needs summary and how_to_try as strings')
      }
      const buildsLeft = state.builds < MAX_BUILDS
      if (buildsLeft && (!state.lastBuildOk || state.dirtySinceBuild)) {
        throw new ToolError(state.dirtySinceBuild
          ? 'Files changed since the last build. Run run_build and confirm it passes before finishing.'
          : 'The last build did not pass. Fix it and run run_build again before finishing.')
      }
      state.finished = { summary: input.summary, howToTry: input.how_to_try }
      return 'done'
    }

    default:
      throw new ToolError(`unknown tool ${name}`)
  }
}

interface AgentResult {
  turns: number
  finished: AgentState['finished']
  written: string[]
  builds: number
}

// The agent loop. History is append-only: each assistant turn goes back
// verbatim (thinking blocks included) and each batch of tool results is one
// user message, so the prompt cache keeps hitting as the conversation grows.
async function runAgent(ideaId: string, root: string, brief: string): Promise<AgentResult> {
  const client = getClient()
  const state: AgentState = { root, written: new Set(), builds: 0, lastBuildOk: false, dirtySinceBuild: false, finished: null }
  const messages: Anthropic.MessageParam[] = [{ role: 'user', content: brief }]
  let turns = 0
  let nudges = 0
  let jsonRetries = 0

  while (turns < MAX_TURNS && !state.finished) {
    turns++
    setStageProgress(ideaId, `agent · turn ${turns} of ${MAX_TURNS} · ${state.written.size} file(s) written · ${state.builds} build(s)`)

    // Streamed so a turn that writes several large files cannot hit an HTTP
    // timeout. The top-level cache_control caches the growing prefix.
    const stream = client.messages.stream({
      model: MODELS.slice,
      max_tokens: 32000,
      system: SLICE_SYSTEM,
      tools: TOOLS,
      cache_control: { type: 'ephemeral' },
      output_config: { effort: 'high' },
      messages,
    })

    let message: Anthropic.Message
    try {
      message = await stream.finalMessage()
      jsonRetries = 0
    } catch (err) {
      // A tool input that could not be parsed at all rejects here. Retry that
      // turn a couple of times; anything from the API itself is a real failure.
      if (err instanceof Anthropic.APIError || jsonRetries++ >= 2) throw err
      turns--
      continue
    }

    logUsage('slice', ideaId, message.usage.input_tokens, message.usage.output_tokens, {
      model: MODELS.slice,
      cacheReadTokens: message.usage.cache_read_input_tokens ?? 0,
      cacheWriteTokens: message.usage.cache_creation_input_tokens ?? 0,
    })

    if (message.stop_reason === 'refusal') {
      const category = (message as { stop_details?: { category?: string | null } | null }).stop_details?.category
      throw new Error(`The model declined to continue${category ? ` (${category})` : ''}`)
    }

    messages.push({ role: 'assistant', content: message.content })
    const toolUses = message.content.filter((b): b is Anthropic.ToolUseBlock => b.type === 'tool_use')

    if (message.stop_reason === 'pause_turn') continue

    if (!toolUses.length) {
      if (++nudges > 2) break
      messages.push({
        role: 'user',
        content: message.stop_reason === 'max_tokens'
          ? 'That reply hit the output limit before any tool call completed. Continue in smaller steps, one file per write_file call.'
          : 'Keep working through the tools. When the feature is built and run_build passes, call finish.',
      })
      continue
    }

    // Every tool_use gets exactly one tool_result, all in a single user message.
    const truncated = message.stop_reason === 'max_tokens'
    const results: Anthropic.ToolResultBlockParam[] = []
    for (const call of toolUses) {
      if (truncated) {
        // A cut-off input usually still parses, as a partial object. Never run it.
        results.push({
          type: 'tool_result', tool_use_id: call.id, is_error: true,
          content: 'The reply hit the output limit, so this call may be incomplete and was not run. Send it again, with fewer or smaller files per reply.',
        })
        continue
      }
      try {
        results.push({ type: 'tool_result', tool_use_id: call.id, content: await execTool(state, call.name, call.input) })
      } catch (err) {
        if (!(err instanceof ToolError)) console.error(`[slice ${ideaId}] tool ${call.name} threw:`, err)
        results.push({
          type: 'tool_result', tool_use_id: call.id, is_error: true,
          content: err instanceof Error ? err.message : String(err),
        })
      }
    }
    messages.push({ role: 'user', content: results })
  }

  return { turns, finished: state.finished, written: [...state.written].sort(), builds: state.builds }
}

// ── Orchestration ────────────────────────────────────────────────────────────

// Slices are heavy (an install, several builds, a server) so only one runs at
// a time in this process.
const lock = globalThis as typeof globalThis & { _sliceRunning?: string | null }

export function sliceInProgress(): string | null {
  return lock._sliceRunning ?? null
}

// Gate + kickoff. The transition to `slicing` runs synchronously and throws a
// TransitionError if the idea is not in the slice queue (or retrying a failed
// slice), so the route can answer 409 before anything is spawned.
export function startSlice(ideaId: string, actor: 'human' | 'auto' = 'human') {
  if (lock._sliceRunning) throw new Error('Another slice is already building. Try again when it finishes.')
  transition(ideaId, 'slicing', { actor })
  lock._sliceRunning = ideaId
  void runSlice(ideaId).catch(err => console.error('[slice job]', err))
}

// Assumes the idea is already `slicing`. Owns its completion and failure
// transitions and never throws into the caller.
export async function runSlice(ideaId: string) {
  lock._sliceRunning = ideaId
  const partial: Partial<SliceSummary> = {}
  try {
    const idea = getDb().prepare('SELECT id, title, tagline FROM ideas WHERE id = ?')
      .get(ideaId) as { id: string; title: string; tagline: string | null } | undefined
    if (!idea) throw new Error(`Idea ${ideaId} not found`)

    const specRow = getArtifact(ideaId, 'spec', 'json')
    if (!specRow?.content) throw new Error('No spec to build from')
    const spec = JSON.parse(specRow.content) as Spec
    const feature = spec.mvp_scope?.[0]?.trim() || spec.wedge_feature?.trim()
    if (!feature) throw new Error('The spec has no first feature to build')
    const mock = getArtifact(ideaId, 'mock', 'html')

    const dir = sliceDir(idea.title)
    Object.assign(partial, {
      feature, directory: dir, model: MODELS.slice,
      run_command: `cd "${dir}" && npm run dev`,
    })

    setStageProgress(ideaId, 'scaffolding from the template')
    scaffold(dir)
    const templateFiles = new Set(listProjectFiles(dir))

    if (needsInstall(dir)) {
      setStageProgress(ideaId, 'installing dependencies (first run for this idea)')
      const install = await run('npm', ['install', '--no-audit', '--no-fund', '--loglevel=error'], {
        cwd: dir, env: childEnv(), timeoutMs: INSTALL_TIMEOUT_MS, shell: true,
      })
      if (install.code !== 0) {
        partial.build_log_tail = tail(install.output, 60)
        throw new Error(install.timedOut ? 'npm install timed out' : `npm install exited ${install.code}`)
      }
    }

    const brief = composeSliceBrief({
      title: idea.title,
      tagline: idea.tagline,
      feature,
      specJson: specRow.content,
      templateFiles: BRIEF_FILES.map(p => ({ path: p, content: fs.readFileSync(path.join(dir, p), 'utf8') })),
      mockHtml: mock?.content,
    })

    const agent = await runAgent(ideaId, dir, brief)
    Object.assign(partial, {
      turns: agent.turns,
      agent_finished: !!agent.finished,
      agent_summary: agent.finished?.summary ?? null,
      how_to_try: agent.finished?.howToTry ?? null,
      files_written: agent.written,
    })

    // Scope guard: compare what is on disk to what the template shipped.
    const added = listProjectFiles(dir).filter(f => !templateFiles.has(f) && !DIFF_SKIP.has(f))
    partial.files_added = added.length
    partial.scope_flag = added.length > SCOPE_FILE_THRESHOLD
      ? `${added.length} files added to the template (review threshold is ${SCOPE_FILE_THRESHOLD}). Check for work beyond the one feature.`
      : null

    // The authoritative build: ours, not the agent's.
    setStageProgress(ideaId, 'final build')
    const build = await runBuild(dir)
    fs.writeFileSync(path.join(dir, 'slice-build.log'), build.output, 'utf8')
    const buildOk = build.code === 0 && !build.timedOut
    Object.assign(partial, {
      build_ok: buildOk,
      build_exit_code: build.code,
      build_log_tail: tail(build.output, 120).slice(-12000),
    })

    let smoke: { status: number | null; ok: boolean; output: string } = { status: null, ok: false, output: '' }
    if (buildOk) {
      setStageProgress(ideaId, 'smoke test: starting the app and requesting /')
      smoke = await smokeTest(dir)
    }
    Object.assign(partial, { smoke_status: smoke.status, smoke_ok: smoke.ok })

    saveSummary(ideaId, partial, build.output + (smoke.output ? `\n\n--- smoke test server output ---\n${smoke.output}` : ''))

    if (!buildOk) {
      return transition(ideaId, 'slice_failed', {
        actor: 'auto', error: build.timedOut ? 'the build timed out' : `the build exited ${build.code}`,
      })
    }
    if (!smoke.ok) {
      return transition(ideaId, 'slice_failed', {
        actor: 'auto', error: smoke.status ? `smoke test: GET / returned ${smoke.status}` : 'smoke test: the app did not respond on /',
      })
    }
    return transition(ideaId, 'slice_built', { actor: 'auto', reason: `build green, GET / ${smoke.status}` })
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err)
    console.error(`[runSlice ${ideaId}]`, message)
    try { saveSummary(ideaId, { ...partial, error: message }, partial.build_log_tail ?? '') } catch { /* best effort */ }
    try { transition(ideaId, 'slice_failed', { actor: 'auto', error: message }) } catch (e) { console.error('[runSlice] could not record failure:', e) }
    return null
  } finally {
    lock._sliceRunning = null
  }
}

function saveSummary(ideaId: string, partial: Partial<SliceSummary>, log: string) {
  const summary: Omit<SliceSummary, 'version'> = {
    feature: partial.feature ?? '',
    directory: partial.directory ?? '',
    run_command: partial.run_command ?? '',
    model: partial.model ?? MODELS.slice,
    turns: partial.turns ?? 0,
    agent_finished: partial.agent_finished ?? false,
    agent_summary: partial.agent_summary ?? null,
    how_to_try: partial.how_to_try ?? null,
    build_ok: partial.build_ok ?? false,
    build_exit_code: partial.build_exit_code ?? null,
    build_log_tail: partial.build_log_tail ?? '',
    smoke_status: partial.smoke_status ?? null,
    smoke_ok: partial.smoke_ok ?? false,
    files_written: partial.files_written ?? [],
    files_added: partial.files_added ?? 0,
    scope_flag: partial.scope_flag ?? null,
    error: partial.error ?? null,
    created_at: new Date().toISOString(),
  }
  addArtifact({ ideaId, stage: 'slice', kind: 'json', content: JSON.stringify(summary), path: partial.directory ?? null })
  addArtifact({ ideaId, stage: 'slice', kind: 'log', content: log.slice(-MAX_OUTPUT) })
}

// ── Nightly run (called by the scheduler) ────────────────────────────────────

// Builds every idea a human has queued. One at a time, each isolated: a failed
// slice is recorded on its idea and the queue moves on.
export async function runNightlySlices() {
  const queued = getDb().prepare(`SELECT id FROM ideas WHERE status = 'selected_slice' ORDER BY created_at`).all() as { id: string }[]
  console.log(`[slice] Nightly run: ${queued.length} idea(s) queued`)
  let built = 0, failed = 0
  for (const { id } of queued) {
    if (lock._sliceRunning) { console.log('[slice] a slice is already running; skipping the rest of the nightly queue'); break }
    try {
      transition(id, 'slicing', { actor: 'auto', reason: 'nightly run' })
      const result = await runSlice(id) as { status?: string } | null
      if (result?.status === 'slice_built') built++; else failed++
    } catch (err) {
      failed++
      console.error(`[slice] nightly ${id} skipped:`, err instanceof Error ? err.message : err)
    }
  }
  console.log(`[slice] Nightly run done: ${built} built, ${failed} failed`)
}

